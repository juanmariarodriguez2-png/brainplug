"""Regenerate the files the web app shares with the Python package.

    python scripts/build_web.py

* docs/app/engine/stopwords.js   the stop-word list (brainprint/stopwords.py)
* docs/app/viewer.tpl.html       the viewer template with three.js inlined
* docs/demo.html, docs/demo_es.html   the live demo shown on the site

tests/test_web.py fails when the first two are out of date.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from brainprint import analysis, demo  # noqa: E402
from brainprint.pipeline import local_tz  # noqa: E402
from brainprint.render import render, template_html  # noqa: E402
from brainprint.stopwords import STOP_WORDS  # noqa: E402

APP = ROOT / "docs" / "app"


def stopwords_js() -> str:
    return ("// Generated by scripts/build_web.py from brainprint/stopwords.py. Do not edit.\n"
            f"export const STOP_WORDS = {json.dumps(STOP_WORDS, ensure_ascii=False)};\n")


def outputs() -> dict[Path, str]:
    return {APP / "engine" / "stopwords.js": stopwords_js(), APP / "viewer.tpl.html": template_html()}


def main() -> None:
    for path, text in outputs().items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    if "--demo" in sys.argv:
        items = demo.generate(600)
        for lang, name in (("en", "demo.html"), ("es", "demo_es.html")):
            payload = analysis.analyse(items, tz=local_tz("UTC"), n_topics=9, title="Demo Brainprint")
            render(payload, ROOT / "docs" / name, lang=lang)
            print(f"wrote docs/{name}")


if __name__ == "__main__":
    main()
